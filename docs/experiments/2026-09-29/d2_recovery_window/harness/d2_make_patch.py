def apply_runtime_patch() -> None:
    import codontrace.engine_runtime as engine_runtime
    import codontrace.life_loop.engine_ledger_coupler as coupler

    engine_ns = dict(vars(engine_runtime))
    if "PopulationState" not in engine_ns:
        from codontrace.genesis.population import PopulationState as _Pop  # noqa: PLC0415

        engine_ns["PopulationState"] = _Pop
    if "World2D" not in engine_ns:
        from codontrace.world import World2D as _World  # noqa: PLC0415

        engine_ns["World2D"] = _World
    exec("class _EnginePatch:\n" + ENGINE_NEW, engine_ns)  # noqa: S102 - prototype of the patch text
    patch_cls = engine_ns["_EnginePatch"]
    capture = patch_cls.__dict__["capture_fork"]
    from_fork = patch_cls.__dict__["from_fork"]
    engine_runtime.GenesisEngine.capture_fork = (
        capture.__func__ if isinstance(capture, classmethod) else capture
    )
    engine_runtime.GenesisEngine.from_fork = classmethod(
        from_fork.__func__ if isinstance(from_fork, classmethod) else from_fork
    )
    # tick-offset initialisation for engines built before the patch
    original_init = engine_runtime.GenesisEngine.from_spec.__func__

    def from_spec(cls, spec, *, generation_boundary_observers=None):  # type: ignore[no-untyped-def]
        engine = original_init(cls, spec, generation_boundary_observers=generation_boundary_observers)
        engine._tick_offset = 0
        return engine

    engine_runtime.GenesisEngine.from_spec = classmethod(from_spec)

    coupler_ns = dict(vars(coupler))
    exec(COUPLER_NEW, coupler_ns)  # noqa: S102 - prototype of the patch text
    coupler.bind_nodes_to_organisms = coupler_ns["bind_nodes_to_organisms"]

    import re

    original_apply = coupler.apply_ledger_feedback_to_engine
    source = _copy.deepcopy(original_apply.__code__)
    # Inject the new branch by re-compiling the function with the block inserted.
    import inspect

    fn_src = inspect.getsource(original_apply)
    fn_src = fn_src.replace(COUPLER_ALLOC_ANCHOR, COUPLER_ALLOC_REPLACEMENT, 1)
    fn_src = fn_src.replace(
        "    g = int(generation_index)\n",
        "    g = int(generation_index)\n" + COUPLER_BLOCK,
        1,
    )
    fn_src = re.sub(r"^def apply_ledger_feedback_to_engine", "def _patched_apply", fn_src, count=1)
    exec(fn_src, coupler_ns)  # noqa: S102 - prototype of the patch text
    coupler.apply_ledger_feedback_to_engine = coupler_ns["_patched_apply"]
    del source


def evidence_fork() -> dict[str, Any]:
    from codontrace.engine_runtime import GenesisEngine
    from codontrace.genesis.campaigns.discovery_q_20260928_idea4 import (
        RECOVERY_TOKEN_KEY,
        _apply_ops_cell,
        harvest_rare_class_yield,
    )
    from codontrace.genesis.campaigns.discovery_q_20260928_idea4_engine import build_idea4_engine_spec
    from codontrace.life_loop.contact_atp_ledger import build_engine_scaffold_ledger
    from codontrace.life_loop.engine_ledger_coupler import (
        EngineCoupledLedgerObserver,
        population_path_fingerprint,
    )

    seed = 5501
    t_int = 10
    fork_holder: dict[str, Any] = {}

    def build(horizon: int) -> tuple[Any, Any, dict[str, Any], list[str]]:
        holder: dict[str, Any] = {"engine": None}
        paths: list[str] = []
        ledger = build_engine_scaffold_ledger(seed=seed)
        observer = EngineCoupledLedgerObserver(
            engine_holder=holder,
            ledger=ledger,
            schedule={},
            harvest_fn=harvest_rare_class_yield,
            auto_advance=True,
            feedback_enabled=True,
        )

        class _Rec:
            def __call__(self, *, generation_index: int) -> None:
                del generation_index
                paths.append(population_path_fingerprint(holder["engine"]))

        spec = build_idea4_engine_spec(seed=seed, tick_count=horizon, population=8)
        engine = GenesisEngine.from_spec(spec, generation_boundary_observers=(observer, _Rec()))
        holder["engine"] = engine
        return engine, spec, holder, paths

    # 1) history to t_int, capture the fork there
    engine, spec, holder, paths = build(t_int)
    engine.run_ticks()
    fork = engine.capture_fork(parent_snapshot_id="d2-probe")
    fork_holder["fork"] = fork

    # 2) continue the original for 5 more ticks
    engine.run_ticks(ticks=5)
    original_continuation = list(paths[t_int:])

    # 3) restore the fork and continue the same 5 ticks
    restored = GenesisEngine.from_fork(spec, fork)
    restored_ids_immediately = sorted(str(o.id) for o in restored.runner.population.organisms)
    restored_paths: list[str] = []

    class _Rec2:
        def __call__(self, *, generation_index: int) -> None:
            del generation_index
            restored_paths.append(population_path_fingerprint(restored_engine))

    restored_engine = restored
    restored_engine.generation_boundary_observers.append(_Rec2())
    restored_engine.run_ticks(ticks=5)

    # 4) branch the same fork into two arms and confirm they differ
    def branch(arm: str) -> list[str]:
        holder_b: dict[str, Any] = {"engine": None}
        seen: list[str] = []
        led = build_engine_scaffold_ledger(seed=seed)

        def _op(l: Any, g: int) -> dict[str, Any]:
            del g
            return {"cell": _apply_ops_cell(l, arm)}

        obs = EngineCoupledLedgerObserver(
            engine_holder=holder_b,
            ledger=led,
            schedule={t_int + 1: [_op]},
            harvest_fn=harvest_rare_class_yield,
            auto_advance=True,
            feedback_enabled=True,
            feedback_allocation="incident_endpoints_realised",
        )

        class _R:
            def __call__(self, *, generation_index: int) -> None:
                del generation_index
                seen.append(population_path_fingerprint(holder_b["engine"]))

        eng = GenesisEngine.from_fork(spec, fork, generation_boundary_observers=(obs, _R()))
        holder_b["engine"] = eng
        eng.run_ticks(ticks=5)
        return seen

    named = branch("cut_named_scaffold")
    matched = branch("cut_matched_random")

    from codontrace.genesis.population import PopulationState as _PopulationState

    fork_population = _PopulationState.from_dict(dict(fork["population"]))
    captured_ids = sorted(str(o.id) for o in fork_population.organisms)
    restored_ids = restored_ids_immediately
    return {
        "fork_capture_ok": True,
        "fork_tick_index": fork["tick_index"],
        "fork_has_rng_state": "state" in fork["rng"],
        "fork_has_population": bool(fork["population"].get("organisms")),
        "continuation_identical": original_continuation == restored_paths,
        "n_continuation_ticks": len(restored_paths),
        "parent_child_ids_preserved": captured_ids == restored_ids,
        "n_organisms_forked": len(captured_ids),
        "branch_named_paths": named,
        "branch_matched_paths": matched,
        "branches_differ": named != matched,
        "fork_after_original": fork_holder["fork"]["tick_index"],
    }


def evidence_topology() -> dict[str, Any]:
    from codontrace.engine_runtime import GenesisEngine
    from codontrace.genesis.campaigns.discovery_q_20260928_idea4 import (
        RECOVERY_TOKEN_KEY,
        _apply_ops_cell,
        harvest_rare_class_yield,
    )
    from codontrace.genesis.campaigns.discovery_q_20260928_idea4_engine import build_idea4_engine_spec
    from codontrace.life_loop.contact_atp_ledger import build_engine_scaffold_ledger
    from codontrace.life_loop.engine_ledger_coupler import (
        EngineCoupledLedgerObserver,
        population_path_fingerprint,
    )

    seed = 5501
    t_int = 10

    def run_arm(arm: str, allocation: str) -> dict[str, Any]:
        holder: dict[str, Any] = {"engine": None}
        paths: list[str] = []
        ledger = build_engine_scaffold_ledger(seed=seed)

        def _op(l: Any, g: int) -> dict[str, Any]:
            del g
            l.relocate_recovery_token(RECOVERY_TOKEN_KEY, remove=False, new_payload="relocated_engine")
            return {"cell": _apply_ops_cell(l, arm)}

        obs = EngineCoupledLedgerObserver(
            engine_holder=holder,
            ledger=ledger,
            schedule={t_int: [_op]},
            harvest_fn=harvest_rare_class_yield,
            auto_advance=True,
            feedback_enabled=True,
            feedback_allocation=allocation,
        )

        class _R:
            def __call__(self, *, generation_index: int) -> None:
                del generation_index
                paths.append(population_path_fingerprint(holder["engine"]))

        spec = build_idea4_engine_spec(seed=seed, tick_count=t_int + 5, population=8)
        engine = GenesisEngine.from_spec(spec, generation_boundary_observers=(obs, _R()))
        holder["engine"] = engine
        engine.run_ticks()
        fb = obs.feedback_history[t_int - 1]
        return {
            "arm": arm,
            "allocation": allocation,
            "paths": paths,
            "feedback": {k: fb.get(k) for k in ("burden", "burden_edge_changes", "total_debited", "endpoint_map", "endpoint_map_is_contact_physics", "contact_structure_effect_identified", "topology_effect_identified", "per_organism_realised_debit", "unbound_nodes", "n_edge_changes")},
        }

    before_named = run_arm("cut_named_scaffold", "global_smear")
    before_matched = run_arm("cut_matched_random", "global_smear")
    after_named = run_arm("cut_named_scaffold", "incident_endpoints_realised")
    after_matched = run_arm("cut_matched_random", "incident_endpoints_realised")
    return {
        "before_patch": {
            "named_final": before_named["paths"][-1],
            "matched_final": before_matched["paths"][-1],
            "identical": before_named["paths"] == before_matched["paths"],
            "count_penalty_terms_identical": before_named["feedback"]["burden_edge_changes"]
            == before_matched["feedback"]["burden_edge_changes"],
        },
        "after_patch": {
            "named_final": after_named["paths"][-1],
            "matched_final": after_matched["paths"][-1],
            "identical": after_named["paths"] == after_matched["paths"],
            "differ": after_named["paths"] != after_matched["paths"],
            "named_recipients": sorted((after_named["feedback"]["per_organism_realised_debit"] or {}).keys()),
            "matched_recipients": sorted((after_matched["feedback"]["per_organism_realised_debit"] or {}).keys()),
            "named_identified": after_named["feedback"]["contact_structure_effect_identified"],
            "matched_identified": after_matched["feedback"]["contact_structure_effect_identified"],
            "count_penalty_terms_identical": after_named["feedback"]["burden_edge_changes"]
            == after_matched["feedback"]["burden_edge_changes"]
            == 0.0,
            "named_unbound": after_named["feedback"]["unbound_nodes"],
        },
    }


def main() -> int:
    meta = write_patch()
    apply_runtime_patch()
    started = time.time()
    result = {"patch": meta, "round": 1, "probe": "d2_unblocking_patch"}
    result["fork_evidence"] = evidence_fork()
    result["topology_evidence"] = evidence_topology()
    result["seconds"] = round(time.time() - started, 2)
    (D2 / "patch_evidence.json").write_text(json.dumps(result, indent=2, sort_keys=True, default=str), encoding="utf-8")
    print(json.dumps({k: v for k, v in result.items() if k != "patch"}, indent=1, default=str)[:2600])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
