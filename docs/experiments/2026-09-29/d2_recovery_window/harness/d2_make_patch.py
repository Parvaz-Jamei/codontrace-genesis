def build_patched_texts() -> tuple[str, str, str, str]:
    engine_text = ENGINE_PATH.read_text(encoding="utf-8")
    coupler_text = COUPLER_PATH.read_text(encoding="utf-8")
    patched_engine = engine_text.replace(
        BASE_LINE_OLD, BASE_LINE_NEW, 1
    ).replace(
        INDEX_LINE_OLD, INDEX_LINE_NEW, 1
    )
    anchor = "    def snapshot(self) -> GenesisSnapshot:\n"
    assert anchor in patched_engine
    patched_engine = patched_engine.replace(anchor, ENGINE_NEW + "\n" + anchor, 1)
    patched_coupler = coupler_text.replace(COUPLER_ALLOC_ANCHOR, COUPLER_ALLOC_REPLACEMENT, 1)
    n_anchor = "def _structural_delta("
    assert n_anchor in patched_coupler
    patched_coupler = patched_coupler.replace(n_anchor, COUPLER_NEW + "\n" + n_anchor, 1)
    block_anchor = "    g = int(generation_index)\n"
    assert block_anchor in patched_coupler
    patched_coupler = patched_coupler.replace(block_anchor, block_anchor + COUPLER_BLOCK, 1)
    return engine_text, patched_engine, coupler_text, patched_coupler


def write_patch() -> dict[str, Any]:
    engine_text, patched_engine, coupler_text, patched_coupler = build_patched_texts()
    diff = list(
        difflib.unified_diff(
            engine_text.splitlines(keepends=True),
            patched_engine.splitlines(keepends=True),
            fromfile="a/src/codontrace/engine_runtime.py",
            tofile="b/src/codontrace/engine_runtime.py",
            n=3,
        )
    ) + list(
        difflib.unified_diff(
            coupler_text.splitlines(keepends=True),
            patched_coupler.splitlines(keepends=True),
            fromfile="a/src/codontrace/life_loop/engine_ledger_coupler.py",
            tofile="b/src/codontrace/life_loop/engine_ledger_coupler.py",
            n=3,
        )
    )
    patch_path = D2 / "PROPOSED_CHANGE.patch"
    patch_path.write_text("".join(diff), encoding="utf-8")
    return {
        "patch_path": str(patch_path),
        "patch_lines": len(diff),
        "patch_sha256": __import__("hashlib").sha256(patch_path.read_bytes()).hexdigest(),
        "engine_insert_lines": ENGINE_NEW.count("\n"),
        "coupler_insert_lines": (COUPLER_NEW + COUPLER_BLOCK).count("\n"),
    }


